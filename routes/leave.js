// ── Active leave on a given date (used by attendance to auto-mark on-leave staff) ──
router.get('/active', async (req, res) => {
  try {
    const date = req.query.date;
    if (!date) return res.status(400).json({ error: 'date required' });
    const rows = await dbAll(`SELECT b.*, lt.Name AS LeaveTypeName, lt.Color AS LeaveTypeColor, lt.Paid
      FROM tblLeaveBooking b
      JOIN tblLeaveType lt ON lt.LeaveTypeID = b.LeaveTypeID
      WHERE b.Status='Approved' AND b.StartDate <= ? AND b.EndDate >= ? AND (b.TenantID=? OR b.TenantID IS NULL)`, [date, date, tenantOf(req)]);
    res.json(rows);
  } catch (e) { res.status(500).json({ error: e.message }); }
});

